using Apolice.Api.IntegrationTests.Infraestrutura.Suporte;
using Apolice.Infrastructure.Persistence;
using Apolice.Infrastructure.Persistence.Migracao;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;

namespace Apolice.Api.IntegrationTests.Infraestrutura;

public sealed class MigrationsTests(PostgresFixture postgres) : IAsyncLifetime
{
    private static readonly string[] TabelasDoSpec =
    [
        "usuarios", "refresh_tokens", "produtos", "coberturas_produto", "cotacoes", "cotacao_itens", "cotacao_fatores",
        "apolices", "apolice_coberturas", "endossos", "sinistros", "sinistro_historico", "notificacoes", "numeradores",
        "outbox_mensagens", "mensagens_processadas", "idempotencia", "auditoria",
    ];

    private AmbienteInfra _ambiente = null!;

    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    public async ValueTask InitializeAsync() =>
        _ambiente = await AmbienteInfra.CriarAsync(await postgres.CriarBancoAsync("migrations"));

    public async ValueTask DisposeAsync() => await _ambiente.DisposeAsync();

    [Fact]
    public async Task Deve_criar_todas_as_tabelas_do_spec_quando_migrar()
    {
        var tabelas = await _ambiente.ExecutarAsync<ApoliceDbContext, List<string>>(db =>
            db.Database.SqlQueryRaw<string>("SELECT table_name AS \"Value\" FROM information_schema.tables WHERE table_schema = 'public'").ToListAsync(Ct));

        TabelasDoSpec.ShouldBeSubsetOf(tabelas);
    }

    [Fact]
    public async Task Deve_nao_ter_pendencias_quando_migrar_de_novo()
    {
        await _ambiente.ExecutarAsync<IMigradorBanco>(m => m.MigrarAsync(Ct));

        var pendentes = await _ambiente.ExecutarAsync<ApoliceDbContext, IEnumerable<string>>(db => db.Database.GetPendingMigrationsAsync(Ct));
        pendentes.ShouldBeEmpty();
    }

    // Prova o que o DsqlMigrationRunner manda ao DSQL: o DDL das migrations, comando a comando, depois da transformação.
    [Fact]
    public async Task Deve_gerar_ddl_compativel_com_dsql_quando_transformar_as_migrations()
    {
        var comandos = await _ambiente.ExecutarAsync<ApoliceDbContext, List<string>>(db => Task.FromResult(ComandosTransformados(db)));

        comandos.ShouldNotBeEmpty();
        comandos.Where(c => c.StartsWith("CREATE TABLE", StringComparison.Ordinal)).ShouldAllBe(c => c.StartsWith("CREATE TABLE IF NOT EXISTS ", StringComparison.Ordinal));
        var indices = comandos.Where(c => c.Contains(" INDEX ", StringComparison.Ordinal)).ToList();
        indices.ShouldNotBeEmpty();
        indices.ShouldAllBe(c => c.Contains("INDEX ASYNC IF NOT EXISTS ", StringComparison.Ordinal));
        foreach (var proibido in new[] { "jsonb", "serial", "identity", "sequence", "trigger", "extension", "default ", " where " })
        {
            comandos.ShouldAllBe(c => !c.Contains(proibido, StringComparison.OrdinalIgnoreCase), $"DDL com '{proibido}'");
        }
    }

    [Theory]
    [InlineData("CREATE TABLE t (id uuid, dados jsonb)")]
    [InlineData("CREATE TABLE t (id integer GENERATED BY DEFAULT AS IDENTITY)")]
    [InlineData("CREATE SEQUENCE s")]
    [InlineData("CREATE INDEX ix ON t (a) WHERE b IS NULL")]
    [InlineData("CREATE EXTENSION pgcrypto")]
    public void Deve_recusar_ddl_que_o_dsql_nao_suporta(string ddl) =>
        Should.Throw<InvalidOperationException>(() => TransformadorSqlDsql.Transformar(ddl));

    [Theory]
    [InlineData("CREATE TABLE x (id uuid)", "CREATE TABLE IF NOT EXISTS x (id uuid)")]
    [InlineData("CREATE UNIQUE INDEX ix_a ON t (a);", "CREATE UNIQUE INDEX ASYNC IF NOT EXISTS ix_a ON t (a);")]
    [InlineData("CREATE INDEX ix_b ON t (b, c);", "CREATE INDEX ASYNC IF NOT EXISTS ix_b ON t (b, c);")]
    [InlineData("ALTER TABLE t ADD COLUMN c text;", "ALTER TABLE t ADD COLUMN IF NOT EXISTS c text;")]
    [InlineData("CREATE TABLE IF NOT EXISTS x (id uuid)", "CREATE TABLE IF NOT EXISTS x (id uuid)")]
    public void Deve_adaptar_ddl_para_o_dsql(string original, string esperado) =>
        TransformadorSqlDsql.Transformar(original).ShouldBe(esperado);

    [Fact]
    public async Task Deve_usar_tabela_de_historico_do_ef_quando_migrar()
    {
        var aplicadas = await _ambiente.ExecutarAsync<ApoliceDbContext, IEnumerable<string>>(db => db.Database.GetAppliedMigrationsAsync(Ct));
        aplicadas.ShouldContain(id => id.EndsWith("_Inicial", StringComparison.Ordinal));
    }

    private static List<string> ComandosTransformados(ApoliceDbContext db)
    {
        var assembly = db.GetService<IMigrationsAssembly>();
        var gerador = db.GetService<IMigrationsSqlGenerator>();
        var inicializador = db.GetService<IModelRuntimeInitializer>();
        return
        [
            .. assembly.Migrations.Values
                .Select(tipo => assembly.CreateMigration(tipo, db.Database.ProviderName!))
                .SelectMany(m => gerador.Generate(m.UpOperations, m.TargetModel is { } alvo ? inicializador.Initialize(alvo) : null))
                .Select(c => TransformadorSqlDsql.Transformar(c.CommandText)),
        ];
    }
}
